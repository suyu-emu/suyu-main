const std::string kFakeKey = "00112233445566778899aabbccddeeff";

void Write(const fs::path& path, const std::string& bytes) {
    fs::create_directories(path.parent_path());
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    out.write(bytes.data(), static_cast<std::streamsize>(bytes.size()));
}

std::string Read(const fs::path& path) {
    std::ifstream in(path, std::ios::binary);
    return {std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()};
}

std::string Nso() {
    std::string bytes(0x200, '\0');
    bytes.replace(0, 4, "NSO0");
    return bytes;
}

std::string Npdm() {
    std::string bytes(0x80, '\0');
    bytes.replace(0, 4, "META");
    return bytes;
}

std::string RomFs() {
    std::string bytes(0x200, '\0');
    bytes[0] = 0x50;
    return bytes;
}

std::string KeyText() {
    return "; synthetic placeholder, not a real key\nmaster_key_00 = " + kFakeKey + kFakeKey +
           "\nheader_key = " + kFakeKey + kFakeKey + "\n";
}

bool HasRule(const std::vector<Finding>& findings, const std::string& path,
             const std::string& rule) {
    for (const auto& finding : findings) {
        if (finding.path == path && finding.rule == rule) {
            return true;
        }
    }
    return false;
}

std::map<std::string, std::string> Snapshot(const fs::path& root) {
    std::map<std::string, std::string> files;
    for (const auto& entry : fs::recursive_directory_iterator(root)) {
        if (entry.is_regular_file()) {
            files[fs::relative(entry.path(), root).generic_string()] = Read(entry.path());
        }
    }
    return files;
}

/// A directory link: a symlink where allowed, else an NTFS junction.
bool MakeDirectoryLink(const fs::path& link, const fs::path& target) {
    std::error_code ec;
    fs::create_directory_symlink(target, link, ec);
    if (!ec) {
        return true;
    }
#ifdef _WIN32
    const std::wstring command = L"cmd /c mklink /J \"" + link.wstring() + L"\" \"" +
                                 target.wstring() + L"\" >nul 2>nul";
    return _wsystem(command.c_str()) == 0 && fs::exists(link);
#else
    return false;
#endif
}

bool MakeFileLink(const fs::path& link, const fs::path& target) {
    std::error_code ec;
    fs::create_symlink(target, link, ec);
    return !ec;
}

