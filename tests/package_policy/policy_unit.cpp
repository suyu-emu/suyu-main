void TestSignatures() {
    const std::string nsp = "PFS0" + std::string(60, '\0');
    CHECK(MatchContentSignature(std::span{reinterpret_cast<const std::uint8_t*>(nsp.data()),
                                          nsp.size()})
              .has_value());
    std::string xci(0x200, '\0');
    xci.replace(0x100, 4, "HEAD");
    CHECK(MatchContentSignature(std::span{reinterpret_cast<const std::uint8_t*>(xci.data()),
                                          xci.size()})
              .has_value());
    const std::string text = "hello world";
    CHECK(!MatchContentSignature(std::span{reinterpret_cast<const std::uint8_t*>(text.data()),
                                           text.size()})
               .has_value());
}

void TestPaths(const fs::path& root) {
    CHECK(IsWithin(root, root / "a" / "b"));
    CHECK(IsWithin(root, root));
    CHECK(!IsWithin(root / "a", root / "a" / ".." / "b"));
    // A string prefix is not containment.
    CHECK(!IsWithin(root / "pkg", root / "pkg-other" / "x"));
#ifdef _WIN32
    CHECK(IsWithin(root / "Pkg", root / "pKG" / "user"));
#endif
    CHECK(Overlaps(root / "a", root / "a" / "b") && Overlaps(root / "a" / "b", root / "a"));
    CHECK(!Overlaps(root / "a", root / "b"));
    CHECK(!AcceptInstalledRoot(root / "pkg", root / "pkg" / "user").has_value());
    CHECK(!AcceptInstalledRoot(root / "pkg", root / "pkg").has_value());
    CHECK(AcceptInstalledRoot(root / "pkg", root / "installed" / "user").has_value());
}

void TestExeFsPlan(const fs::path& root) {
    const fs::path exefs = root / "exefs-valid";
    Write(exefs / "main", Nso());
    Write(exefs / "rtld", Nso());
    Write(exefs / "subsdk0", Nso());
    Write(exefs / "main.npdm", Npdm());
    Write(exefs / "romfs.bin", RomFs());
    Write(exefs / "desktop.ini", "[.ShellClassInfo]\n");
    fs::create_directories(exefs / "romfs");
    ExeFsPlan plan = PlanExtractedExeFs(exefs);
    CHECK(plan.Ok());
    CHECK(plan.files.size() == 5);
    CHECK(plan.ignored.size() == 2);
    CHECK(plan.Find(ExeFsRole::RomFs) != nullptr);

    // Unknown siblings and dummy key sentinels are rejected, not skipped.
    const fs::path dirty = root / "exefs-dirty";
    fs::copy(exefs, dirty, fs::copy_options::recursive);
    Write(dirty / "notes.txt", "unrelated");
    Write(dirty / "prod.keys", KeyText());
    Write(dirty / "Title.Keys_Autogenerated", KeyText());
    Write(dirty / "BOOT0", std::string(64, '\0'));
    Write(dirty / "main.txt", Nso()); // misleading extension
    Write(dirty / "0100000000f02001000000000000000a.tik", "synthetic");
    plan = PlanExtractedExeFs(dirty);
    CHECK(!plan.Ok());
    CHECK(HasRule(plan.rejected, "notes.txt", "unexpected-file"));
    CHECK(HasRule(plan.rejected, "prod.keys", "key-file"));
    CHECK(HasRule(plan.rejected, "Title.Keys_Autogenerated", "key-file"));
    CHECK(HasRule(plan.rejected, "0100000000f02001000000000000000a.tik", "key-file"));
    CHECK(HasRule(plan.rejected, "BOOT0", "firmware"));
    CHECK(HasRule(plan.rejected, "main.txt", "unexpected-file"));

    // A module name holding something else fails format validation.
    const fs::path forged = root / "exefs-forged";
    Write(forged / "main", Nso());
    Write(forged / "sdk", KeyText());
    Write(forged / "main.npdm", "PFS0" + std::string(60, '\0'));
    plan = PlanExtractedExeFs(forged);
    CHECK(HasRule(plan.rejected, "sdk", "invalid-format"));
    CHECK(HasRule(plan.rejected, "main.npdm", "invalid-format"));

    const fs::path no_main = root / "exefs-no-main";
    Write(no_main / "rtld", Nso());
    CHECK(!PlanExtractedExeFs(no_main).Ok());
}

void TestLinks(const fs::path& root) {
    const fs::path outside = root / "outside";
    Write(outside / "prod.keys", KeyText());
    Write(outside / "main", Nso());
    const fs::path exefs = root / "exefs-link";
    Write(exefs / "main", Nso());
    if (MakeDirectoryLink(exefs / "escape", outside)) {
        const ExeFsPlan plan = PlanExtractedExeFs(exefs);
        CHECK(HasRule(plan.rejected, "escape", "link"));
        // A path through a linked folder resolves outside the source root.
        std::string error;
        CHECK(!CopyFileNoFollow(exefs, exefs / "escape" / "main", root / "copied-main", &error));
        CHECK(!fs::exists(root / "copied-main"));
        // Copying a tree that holds a junction fails without following it.
        const fs::path tree = root / "tree-link";
        Write(tree / "save.bin", "save");
        MakeDirectoryLink(tree / "evil", outside);
        CHECK(!CopyTreeNoFollow(tree, root / "tree-copy", &error));
        // Removing a tree deletes the link, never the target.
        CHECK(RemoveTreeNoFollow(tree, &error));
        CHECK(fs::exists(outside / "prod.keys"));
    } else {
        g_skips.push_back("directory link escape (no symlink or junction permission)");
    }
    if (MakeFileLink(exefs / "sdk", outside / "main")) {
        CHECK(HasRule(PlanExtractedExeFs(exefs).rejected, "sdk", "link"));
    } else {
        g_skips.push_back("file symlink escape (symlink creation not permitted)");
    }
    std::string error;
    Write(root / "overlap" / "a.bin", "x");
    CHECK(!CopyTreeNoFollow(root / "overlap", root / "overlap" / "inner", &error));
}

void TestCopy(const fs::path& root) {
    const fs::path source = root / "copy-src";
    Write(source / "a" / "b.bin", "hello");
    std::string error;
    CHECK(CopyFileNoFollow(source, source / "a" / "b.bin", root / "copy-dst.bin", &error));
    CHECK(Read(root / "copy-dst.bin") == "hello");
    // Never over an existing file.
    CHECK(!CopyFileNoFollow(source, source / "a" / "b.bin", root / "copy-dst.bin", &error));
    // Outside the declared root.
    CHECK(!CopyFileNoFollow(source / "a" / "nothing", source / "a" / "b.bin", root / "x.bin",
                            &error));
    CHECK(CopyTreeNoFollow(source, root / "copy-tree", &error));
    CHECK(Read(root / "copy-tree" / "a" / "b.bin") == "hello");
    CHECK(!CopyTreeNoFollow(source, root / "copy-tree", &error)); // exists
    Write(source / "a" / "prod.keys", KeyText());
    CHECK(!CopyTreeNoFollow(source, root / "copy-tree-2", &error));
    fs::remove(source / "a" / "prod.keys");
    Write(source / "a" / "renamed.dat", KeyText());
    CHECK(!CopyTreeNoFollow(source, root / "copy-tree-3", &error));
}

