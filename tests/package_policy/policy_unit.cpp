void TestValidation(const fs::path& root) {
    const std::string title = "0100000000010000";
    std::string error;
    auto staging = CreateStaging(root / "out-validate", &error);
    CHECK(staging.has_value());
    const fs::path pkg = MakePackage(*staging, title);
    CHECK(ValidateLocalExport(pkg, Expect(title)).empty());

    Write(pkg / "user" / "keys" / "prod.keys", KeyText());
    // No game data of any kind: not the ExeFS, not the RomFS, not a container.
    Write(pkg / "exefs" / "main", Nso());
    Write(pkg / "exefs" / "romfs.bin", RomFs());
    Write(pkg / "stray.txt", "x");
    Write(pkg / "user" / "nand" / "user" / "save" / "0000000000000000" /
              "00112233445566778899aabbccddeeff" / "0100000000020000" / "other.bin",
          "other title");
    Write(pkg / "user" / "nand" / "system" / "Contents" / "registered" / "fw.nca", "fw");
    Write(pkg / "mods" / "leftover.txt", "x");
    Write(pkg / "user" / "cache" / "shader" / "0100000000020000" / "vulkan.bin", "x");
    const auto findings = ValidateLocalExport(pkg, Expect(title));
    CHECK(HasRule(findings, "user/keys", "unexpected"));
    CHECK(HasRule(findings, "exefs", "unexpected"));
    CHECK(HasRule(findings, "stray.txt", "unexpected"));
    CHECK(HasRule(findings, "user/nand/system", "unexpected"));
    CHECK(HasRule(findings, "mods/leftover.txt", "unexpected"));
    CHECK(HasRule(findings, "user/cache/shader/0100000000020000", "unexpected"));
    bool other_title = false;
    for (const auto& finding : findings) {
        other_title |= finding.path.find("0100000000020000") != std::string::npos;
    }
    CHECK(other_title);

    // Source exports keep aot_cache; a stray container or key text in it is caught.
    auto source = CreateStaging(root / "out-validate-src", &error);
    const fs::path src_pkg = MakePackage(*source, title);
    auto expect = Expect(title);
    expect.allow_aot_cache = true;
    Write(src_pkg / "aot_cache" / "exefs" / "main" / "src" / "unit0.c", "int x = 1;\n");
    Write(src_pkg / "aot_cache" / "exefs" / "main" / "CMakeLists.txt", "project(x C)\n");
    CHECK(ValidateLocalExport(src_pkg, expect).empty());
    // The game's own modules, bundled segments, a standalone runner or guest dumps
    // never travel with the generated project.
    Write(src_pkg / "aot_cache" / "exefs" / "nso" / "main", Nso());
    Write(src_pkg / "aot_cache" / "exefs" / "main" / "data" / "text.bin", "code");
    Write(src_pkg / "aot_cache" / "exefs" / "main" / "main.c", "int main(void){}\n");
    Write(src_pkg / "aot_cache" / "debug" / "code" / "main" / "b.guest.bin", "code");
    {
        const auto game_data = ValidateLocalExport(src_pkg, expect);
        CHECK(HasRule(game_data, "aot_cache/exefs/nso", "unexpected"));
        CHECK(HasRule(game_data, "aot_cache/exefs/main/data", "unexpected"));
        CHECK(HasRule(game_data, "aot_cache/exefs/main/main.c", "unexpected"));
        CHECK(HasRule(game_data, "aot_cache/debug", "unexpected"));
    }
    fs::remove_all(src_pkg / "aot_cache" / "exefs" / "nso");
    fs::remove_all(src_pkg / "aot_cache" / "exefs" / "main" / "data");
    fs::remove(src_pkg / "aot_cache" / "exefs" / "main" / "main.c");
    fs::remove_all(src_pkg / "aot_cache" / "debug");
    CHECK(ValidateLocalExport(src_pkg, expect).empty());
    Write(src_pkg / "aot_cache" / "game.nsp", "PFS0" + std::string(60, '\0'));
    Write(src_pkg / "aot_cache" / "exefs" / "main" / "src" / "keys.h", KeyText());
    Write(src_pkg / "aot_cache" / "blob.bin", "PFS0" + std::string(60, '\0'));
    Write(src_pkg / "aot_cache" / "exefs" / "main" / "src" / "title.tik", "synthetic");
    const auto src_findings = ValidateLocalExport(src_pkg, expect);
    CHECK(HasRule(src_findings, "aot_cache/game.nsp", "game-container"));
    CHECK(HasRule(src_findings, "aot_cache/exefs/main/src/keys.h", "key-text"));
    CHECK(HasRule(src_findings, "aot_cache/exefs/main/src/title.tik", "key-file"));
    CHECK(HasRule(src_findings, "aot_cache/blob.bin", "signature"));
    // Without allow_aot_cache the whole folder is unexpected.
    CHECK(HasRule(ValidateLocalExport(src_pkg, Expect(title)), "aot_cache", "unexpected"));
    CHECK(RemoveStaging(*staging, &error));
    CHECK(RemoveStaging(*source, &error));
}

void TestPortable(const fs::path& root) {
    const std::string title = "0100000000010000";
    std::string error;
    auto staging = CreateStaging(root / "out-portable", &error);
    CHECK(staging.has_value());
    const fs::path pkg = MakePackage(*staging, title);
    const std::string sealed(0x1000, 'Z');
    Write(pkg / "game" / "base.sealed", sealed);
    Write(pkg / "game" / "update-0.sealed", sealed);
    Write(pkg / "game" / "dlc-0.sealed", sealed);
    Write(pkg / "game" / "dlc-1.sealed", sealed);
    Write(pkg / "game" / "seal.json", "{\"format\": \"suyu-portable-seal-1\"}\n");

    // Without a portable expectation and manifest, sealed files are not part of an export.
    {
        const auto findings = ValidateLocalExport(pkg, Expect(title));
        CHECK(HasRule(findings, "game", "unexpected"));
    }
    auto expect = Expect(title);
    expect.portable = true;
    // The exporter's choice alone is not enough: the manifest must declare it too.
    CHECK(HasRule(ValidateLocalExport(pkg, expect), "export-package.json", "package-type"));
    Write(pkg / "export-package.json", "{\"schema\": \"" + std::string{kExportManifestSchema} +
                                           "\",\n  \"package_type\": \"portable\"}\n");
    CHECK(ManifestDeclaresPortable(Read(pkg / "export-package.json")));
    CHECK(!ManifestDeclaresPortable("{\"package_type\": \"reference\"}"));
    CHECK(ValidateLocalExport(pkg, expect).empty());
    // A manifest that declares a portable export is wrong for any other export.
    CHECK(HasRule(ValidateLocalExport(pkg, Expect(title)), "export-package.json", "package-type"));

    // A container that is not sealed is still refused, whatever its name.
    Write(pkg / "game" / "update-1.sealed", "PFS0" + std::string(60, '\0'));
    Write(pkg / "game" / "dlc-2.sealed", "PFS0" + std::string(60, '\0'));
    Write(pkg / "game" / "dlc-3.sealed", KeyText());
    Write(pkg / "game" / "dlc-x.sealed", sealed);
    Write(pkg / "game" / "dlc-12345.sealed", sealed);
    Write(pkg / "game" / "game.nsp", "x");
    Write(pkg / "game" / "notes.txt", "x");
    Write(pkg / "game" / "prod.keys", KeyText());
    Write(pkg / "game" / "update-2.sealed", KeyText());
    {
        const auto findings = ValidateLocalExport(pkg, expect);
        CHECK(HasRule(findings, "game/update-1.sealed", "signature"));
        CHECK(HasRule(findings, "game/game.nsp", "unexpected"));
        CHECK(HasRule(findings, "game/notes.txt", "unexpected"));
        CHECK(HasRule(findings, "game/prod.keys", "unexpected"));
        CHECK(HasRule(findings, "game/update-2.sealed", "key-text"));
        CHECK(HasRule(findings, "game/dlc-2.sealed", "signature"));
        CHECK(HasRule(findings, "game/dlc-3.sealed", "key-text"));
        CHECK(HasRule(findings, "game/dlc-x.sealed", "unexpected"));
        CHECK(HasRule(findings, "game/dlc-12345.sealed", "unexpected"));
    }
    for (const char* name : {"update-1.sealed", "game.nsp", "notes.txt", "prod.keys",
                             "update-2.sealed", "dlc-2.sealed", "dlc-3.sealed", "dlc-x.sealed",
                             "dlc-12345.sealed"}) {
        fs::remove(pkg / "game" / name);
    }
    // Keys are refused anywhere else in a portable export too.
    Write(pkg / "prod.keys", KeyText());
    CHECK(HasRule(ValidateLocalExport(pkg, expect), "prod.keys", "unexpected"));
    fs::remove(pkg / "prod.keys");
    CHECK(ValidateLocalExport(pkg, expect).empty());

    // Sealed folders only sit at the top of a Windows package, and need both files.
    fs::remove(pkg / "game" / "seal.json");
    CHECK(HasRule(ValidateLocalExport(pkg, expect), "game", "portable-incomplete"));
    CHECK(RemoveStaging(*staging, &error));

    // DLC title IDs: the game's base title, the add-on offset, an index from 1 to 0x7FF.
    CHECK(IsAddOnContentOf(0x0100000000011001, 0x0100000000010000));
    CHECK(IsAddOnContentOf(0x01000000000117FF, 0x0100000000010000));
    CHECK(!IsAddOnContentOf(0x0100000000011000, 0x0100000000010000));
    CHECK(!IsAddOnContentOf(0x0100000000011800, 0x0100000000010000));
    CHECK(!IsAddOnContentOf(0x0100000000010800, 0x0100000000010000));
    CHECK(!IsAddOnContentOf(0x0100000000010000, 0x0100000000010000));
    CHECK(!IsAddOnContentOf(0x0100000000033001, 0x0100000000010000));
    CHECK(!IsAddOnContentOf(0x0100000000011001, 0));
}

void TestPromotion(const fs::path& root) {
    const std::string title = "0100000000010000";
    const fs::path out = root / "out-promote";
    const fs::path dest = out / "Game";
    std::string error;

    // A dirty earlier package: keys, firmware markers, old optional data.
    Write(dest / "README_NATIVE_EXPORT.txt", "old\n");
    Write(dest / "export-package.json",
          "{\"schema\": \"" + std::string{kExportManifestSchema} + "\"}\n");
    Write(dest / "prod.keys", KeyText());
    Write(dest / "user" / "nand" / "system" / "Contents" / "registered" / "BOOT0", "fw");
    Write(dest / "user" / "nand" / "user" / "save" / "0000000000000000" /
              "00112233445566778899aabbccddeeff" / title / "old-save.bin",
          "precious save");
    Write(dest / "user" / "config" / "custom" / "0100000000010000.ini", "[System]\n");
    const auto before = Snapshot(dest);
    CHECK(ClassifyDestination(dest) == Existing::ExporterManaged);

    // Fail policy: structured conflict, nothing touched.
    auto staging = CreateStaging(out, &error);
    const fs::path pkg = MakePackage(*staging, title);
    fs::remove_all(pkg / "user" / "nand"); // this export deselects saves
    auto result = Promote(*staging, dest, ConflictPolicy::Fail);
    CHECK(!result.ok && result.conflict);
    CHECK(Snapshot(dest) == before);
    // Cancelling here: only this run's staging goes, the old package stays.
    CHECK(RemoveStaging(*staging, &error));
    CHECK(!fs::exists(staging->root) && !fs::exists(staging->work));
    CHECK(Snapshot(dest) == before);

    // Replace: the old package is kept whole as a backup, the new one holds
    // only what this export produced.
    staging = CreateStaging(out, &error);
    MakePackage(*staging, title);
    fs::remove_all(staging->root / "user" / "nand");
    result = Promote(*staging, dest, ConflictPolicy::ReplaceWithBackup);
    CHECK(result.ok);
    CHECK(!result.backup_path.empty() && Snapshot(result.backup_path) == before);
    CHECK(!fs::exists(dest / "prod.keys"));
    CHECK(!fs::exists(dest / "user" / "nand"));
    CHECK(!fs::exists(dest / "user" / "config" / "custom"));
    CHECK(ValidateLocalExport(dest, Expect(title)).empty());
    CHECK(RemoveStaging(*staging, &error)); // marker and work folder only
    CHECK(fs::exists(dest / "Game.exe"));

    // KeepBoth picks a fresh name.
    staging = CreateStaging(out, &error);
    MakePackage(*staging, title);
    result = Promote(*staging, dest, ConflictPolicy::KeepBoth);
    CHECK(result.ok && result.final_path.filename() == fs::path{"Game (2)"});
    RemoveStaging(*staging, &error);

    // A foreign folder is never replaced.
    const fs::path foreign = out / "Photos";
    Write(foreign / "holiday.jpg", "jpg");
    staging = CreateStaging(out, &error);
    MakePackage(*staging, title);
    result = Promote(*staging, foreign, ConflictPolicy::ReplaceWithBackup);
    CHECK(!result.ok && result.conflict);
    CHECK(Read(foreign / "holiday.jpg") == "jpg");
    CHECK(RemoveStaging(*staging, &error));

    // A failed move restores the previous package.
    staging = CreateStaging(out, &error);
    const auto current = Snapshot(dest);
    fs::remove_all(staging->root); // nothing left to move in
    result = Promote(*staging, dest, ConflictPolicy::ReplaceWithBackup);
    CHECK(!result.ok);
    CHECK(Snapshot(dest) == current);
    CHECK(RemoveStaging(*staging, &error));

    // Staging owned by someone else is never removed.
    Staging stranger{out, out / ".suyu-export-deadbeef", out / ".suyu-export-deadbeef.work",
                     "deadbeef"};
    Write(stranger.root / "keep.txt", "not ours");
    CHECK(!RemoveStaging(stranger, &error));
    CHECK(fs::exists(stranger.root / "keep.txt"));
    // A destination outside the output folder is refused.
    staging = CreateStaging(out, &error);
    result = Promote(*staging, root / "elsewhere" / "Game", ConflictPolicy::Fail);
    CHECK(!result.ok);
    RemoveStaging(*staging, &error);
}

